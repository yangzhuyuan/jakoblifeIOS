export function healthReminderText(vm, key) {
	return messageKeys[key] ? vm.$t(messageKeys[key]) : key
}

export function reminderDisplayTime(vm, time) {
	const [hours, minutes] = time.split(':').map(Number)
	const period = healthReminderText(vm, hours < 12 ? 'morning' : 'afternoon')
	return `${String(hours % 12 || 12).padStart(2, '0')}:${String(minutes).padStart(2, '0')} ${period}`
}
